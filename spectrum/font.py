FONT = {}
for _ch, _rows in _RAW.items():
    _bits = []
    for _row in _rows.split("/"):
        if len(_row) != GLYPH_W:
            raise ValueError("bad row %r for glyph %r" % (_row, _ch))
        _v = 0
        for _i, _c in enumerate(_row):
            if _c not in ".#":
                raise ValueError("bad pixel %r for glyph %r" % (_c, _ch))
            if _c == "#":
                _v |= 1 << (7 - _i)  # 5 bits, left-aligned in a byte
        _bits.append(_v)
    if len(_bits) != GLYPH_H:
        raise ValueError("glyph %r must have %d rows" % (_ch, GLYPH_H))
    FONT[_ch] = tuple(_bits)

_UNKNOWN = FONT["?"]


def glyph(ch):
    """Return the 8 row-bits of a character, falling back to '?'."""
    ch = ch.upper() if ch.islower() else ch
    return FONT.get(ch, FONT.get(ch.upper(), _UNKNOWN))


def text_width(text, scale=1, spacing=1):
    """Width in pixels of ``text`` drawn with ``scale`` and extra ``spacing``."""
    if not text:
        return 0
    return (len(text) * (GLYPH_W * scale + spacing)) - spacing


def supports(ch):
    return (ch.upper() if ch.islower() else ch) in FONT
